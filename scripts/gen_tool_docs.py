"""Генерация справочника инструментов ``docs/tools/`` из реестра.

Источник истины – ``REGISTRY`` (заполняется импортом toolset-модулей;
auth и extended регистрируются на выброшенном FastMCP-сервере, как в
``tests/contract/test_coverage.py``). Запуск::

    uv run python scripts/gen_tool_docs.py

Создаёт ``docs/tools/index.md`` и ``docs/tools/<toolset>.md``: таблица
инструментов (имя, операция, auth, confirm, описание) и счётчики.
Файлы полностью генерируются – ручные правки затираются перегенерацией.
"""

from __future__ import annotations

import asyncio
import tempfile
from pathlib import Path
from typing import Any

TOOLS_DIR = Path(__file__).resolve().parents[1] / "docs" / "tools"

HEADER = "<!-- GENERATED by scripts/gen_tool_docs.py – do not edit. -->"

# Порядок наборов в справочнике: дефолтные, затем выключенные, extended последним.
TOOLSET_ORDER: tuple[str, ...] = (
    "auth",
    "dictionaries",
    "suggests",
    "vacancies",
    "negotiations",
    "chats",
    "resumes",
    "employer_vacancies",
    "employer_negotiations",
    "employer_resumes",
    "employer_managers",
    "employer_misc",
    "extended",
)

TOOLSET_SUMMARY: dict[str, str] = (
    {
        "auth": "Authorization helpers: profile, OAuth login and logout.",
        "dictionaries": "Public hh.ru dictionaries: areas, industries, roles and more.",
        "suggests": "Search suggestions for areas, companies, skills and keywords.",
        "vacancies": "Vacancy search, similar and related vacancies.",
        "negotiations": "Responses and invitations: lists, states, messages.",
        "chats": "Chats: messages, participants, files, read counters.",
        "resumes": "Resume viewing and call-tracking phone numbers.",
        "employer_vacancies": "Employer vacancy CRUD, drafts, publication, stats.",
        "employer_negotiations": "Employer responses and invitations, mail templates.",
        "employer_resumes": "Resume search (52 params), saved searches, comments.",
        "employer_managers": "Employer managers, settings, access and limits.",
        "employer_misc": "Employer directories, employers info, calls, webhooks.",
        "extended": (
            "UNDOCUMENTED hh.ru API operations, disabled by default: "
            "apply to vacancy, own resumes, artifacts."
        ),
    }
)


def _first_sentence(text: str) -> str:
    """Первая строка описания инструмента без переносов."""
    line = (text or "").strip().splitlines()[0] if text else ""
    return line.replace("|", "\\|")


async def _collect() -> tuple[list[dict[str, Any]], set[str]]:
    """Записи реестра (все toolset'ы) и дефолтные наборы конфигурации."""
    with tempfile.TemporaryDirectory(prefix="ati-hh-mcp-docs-") as tmp:
        # auth регистрируется только внутри register(): выброшенный сервер,
        # изолированное хранилище токенов (файл не создаётся в HOME).
        from fastmcp import Client, FastMCP

        from ati_hh_mcp.config import DEFAULT_TOOLSETS, Config
        from ati_hh_mcp.hh.token_store import TokenStore
        from ati_hh_mcp.registry import REGISTRY
        from ati_hh_mcp.server import TOOLSET_MODULES
        from ati_hh_mcp.toolsets import auth_tools

        server = FastMCP(name="docs-generation")
        config = Config(
            token=None,
            toolsets=DEFAULT_TOOLSETS,
            api_base="https://api.hh.ru",
            ua_email="docs@example.com",
            client_id=None,
            client_secret=None,
            redirect_uri=None,
            api_keys=(),
        )
        for name, module in TOOLSET_MODULES.items():
            if name == "auth":
                auth_tools.register(
                    server, config=config, store=TokenStore(Path(tmp) / "tokens.sqlite3")
                )
            else:
                register_fn = module.register
                register_fn(server)
        async with Client(server) as client:
            described = {
                tool.name: (tool.description or "") for tool in await client.list_tools()
            }

    entries = []
    for entry in REGISTRY.all():
        if entry.toolset not in TOOLSET_ORDER:
            raise SystemExit(f"неизвестный toolset в реестре: {entry.toolset!r}")
        entries.append(
            {
                "name": entry.name,
                "operation": entry.operation_id,
                "toolset": entry.toolset,
                "requires_auth": entry.requires_auth,
                "is_mutation": entry.is_mutation,
                "undocumented": entry.undocumented,
                "description": _first_sentence(described.get(entry.name, "")),
            }
        )
    return entries, set(DEFAULT_TOOLSETS)


def _render_toolset_page(toolset: str, entries: list[dict[str, Any]]) -> str:
    lines = [
        HEADER,
        "",
        f"# Toolset `{toolset}`",
        "",
        TOOLSET_SUMMARY[toolset],
        "",
    ]
    if toolset == "extended":
        lines += [
            "!!! warning",
            "    Operations of this toolset are **not** part of the public hh.ru",
            "    OpenAPI specification and may change without notice. The toolset",
            "    is disabled by default and every tool description carries the",
            "    `[UNDOCUMENTED hh.ru API]` marker.",
            "",
        ]
    lines += [
        f"**{len(entries)} tools.** Mutations require an explicit `confirm=true`"
        " argument; `Auth` marks tools that need an hh.ru token.",
        "",
        "| Tool | Operation | Auth | Confirm | Description |",
        "| --- | --- | :---: | :---: | --- |",
    ]
    for entry in sorted(entries, key=lambda e: e["name"]):
        auth_flag = "yes" if entry["requires_auth"] else "–"
        mutation_flag = "yes" if entry["is_mutation"] else "–"
        marker = "`UNDOC` " if entry["undocumented"] else ""
        lines.append(
            f"| `{entry['name']}` | `{entry['operation']}` | {auth_flag} "
            f"| {mutation_flag} | {marker}{entry['description']} |"
        )
    return "\n".join(lines) + "\n"


def _render_index(
    grouped: dict[str, list[dict[str, Any]]], default_toolsets: set[str]
) -> str:
    lines = [
        HEADER,
        "",
        "# Tool reference",
        "",
        "Every tool maps 1:1 to an operation of the public hh.ru OpenAPI"
        " specification (except the marked undocumented ones). This catalog is"
        " generated from the tool registry by `scripts/gen_tool_docs.py`.",
        "",
        "| Toolset | Tools | Default | Description |",
        "| --- | :---: | :---: | --- |",
    ]
    for toolset in TOOLSET_ORDER:
        if toolset == "auth":
            default_flag = "always on"
        else:
            default_flag = "on" if toolset in default_toolsets else "off"
        count = len(grouped.get(toolset, []))
        lines.append(
            f"| [`{toolset}`]({toolset}.md) | {count} | {default_flag} "
            f"| {TOOLSET_SUMMARY[toolset]} |"
        )
    total = sum(len(items) for items in grouped.values())
    lines += [
        "",
        f"**Total: {total} tools** in {len(TOOLSET_ORDER)} toolsets"
        f" ({sum(1 for t in TOOLSET_ORDER if t != 'auth')} switchable via"
        " `HH_TOOLSETS` plus the always-on `auth`).",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    entries, default_toolsets = asyncio.run(_collect())
    grouped: dict[str, list[dict[str, Any]]] = {
        toolset: [e for e in entries if e["toolset"] == toolset]
        for toolset in TOOLSET_ORDER
    }
    missing = [t for t, items in grouped.items() if not items]
    if missing:
        raise SystemExit(f"toolset'ы без инструментов: {missing}")

    TOOLS_DIR.mkdir(parents=True, exist_ok=True)
    for toolset, toolset_entries in grouped.items():
        (TOOLS_DIR / f"{toolset}.md").write_text(
            _render_toolset_page(toolset, toolset_entries), encoding="utf-8"
        )
    (TOOLS_DIR / "index.md").write_text(
        _render_index(grouped, default_toolsets), encoding="utf-8"
    )

    total = len(entries)
    default_total = sum(
        len(items) for name, items in grouped.items() if name in default_toolsets
    )
    print(f"docs/tools: {len(grouped)} страниц-наборов, {total} инструментов")
    print(f"по умолчанию (включая auth): {default_total}")


if __name__ == "__main__":
    main()
